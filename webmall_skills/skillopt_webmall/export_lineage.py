"""Export a SkillOpt run directory as the C3 skill lineage.

    python -m webmall_skills.skillopt_webmall.export_lineage RUN_DIR [--out webmall_skills/skills/skillopt] [--ledger PATH]

Writes SKILL.md (best skill), HISTORY.md (lineage table), history/ (every candidate,
accepted or rejected, with diff and ranked edits) and run/ (raw provenance).
Deterministic: same run dir -> byte-identical output.
"""
from __future__ import annotations

import argparse
import difflib
import json
import shutil
from pathlib import Path

from webmall_skills.paths import SKILLS_DIR, resolve

DECISIONS = {"accept_new_best": "accepted", "accept": "accepted", "reject": "rejected (gate)"}

README = """# skills/skillopt — C3: SkillOpt-evolved skill

Thesis code output (not upstream WebMall). Generated by
`python -m webmall_skills.skillopt_webmall.export_lineage <run_dir>`; do not edit by hand.

| File | What it is |
|---|---|
| `SKILL.md` | **The C3 skill**: the best skill of the SkillOpt run (highest val F1). |
| `HISTORY.md` | Lineage table: every candidate, its parent, edits, val scores, decision; ★ = became the new best. |
| `SUMMARY.md` | Run summary from `python -m webmall_skills.skillopt_webmall.report <run_dir>`: step timeline; best vs. base vs. no skill on val (F1, efficiency, per task). |
| `history/v0000_base.md` | Seed skill (copy of `skills/base/SKILL.md`). |
| `history/vNNNN.md` | Candidate proposed at step NNNN (accepted or rejected). |
| `history/vNNNN.diff` | Unified diff of the candidate against its parent. |
| `history/vNNNN.edits.json` | Ranked edits SkillOpt applied to the parent. |
| `run/` | Raw provenance: SkillOpt `config.json`, `history.json`, the split manifest, the cost ledger. |

**Provenance chain:** `skills/base/SKILL.md` + `webmall_skills/split/split_v2/` →
SkillOpt run (`webmall_skills/skillopt_webmall/train.py`, config `webmall_skills/skillopt_webmall/configs/c3.yaml`)
→ `run/history.json` → `history/` → `SKILL.md`.
Method: `webmall_skills/skillopt_webmall/DESIGN.md`.
"""


def _read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _edits_summary(edits_path: Path) -> str:
    data = _read_json(edits_path) or {}
    edits = data.get("edits", []) if isinstance(data, dict) else data
    parts = []
    for e in edits:
        text = " ".join(str(e.get("content", "")).split())
        parts.append(f"{e.get('op', '?')}: {text[:60]}{'…' if len(text) > 60 else ''}")
    return "; ".join(parts).replace("|", "\\|")


def build_rows(run_dir: Path) -> list[dict]:
    run_dir = Path(run_dir)
    baseline = _read_json(run_dir / "selection_eval_baseline" / "summary.json") or {}
    rows = [{"version": "v0000", "epoch": "", "parent": "", "edits": "base skill",
             "f1_before": None, "f1_after": baseline.get("soft"), "cr": baseline.get("hard"),
             "decision": "seed", "best": True}]
    current_ver, current_score = "v0000", baseline.get("soft")
    for rec in _read_json(run_dir / "history.json") or []:
        step = rec["step"]
        ver = f"v{step:04d}"
        sdir = run_dir / "steps" / f"step_{step:04d}"
        action = rec.get("action", "")
        row = {"version": ver, "epoch": rec.get("epoch", ""), "parent": current_ver,
               "edits": "", "f1_before": current_score, "f1_after": None, "cr": None,
               "decision": f"skipped ({action})", "best": False}
        if not action.startswith("skip"):
            leak = (sdir / "selection_eval" / "leakage_report.json").exists()
            row.update({
                "edits": _edits_summary(sdir / "ranked_edits.json"),
                "f1_after": None if leak else rec.get("selection_soft"),
                "cr": None if leak else rec.get("selection_hard"),
                "decision": "rejected (test_leakage)" if leak else DECISIONS.get(action, action),
                "best": action == "accept_new_best",
            })
            if action in ("accept", "accept_new_best"):
                current_ver, current_score = ver, rec.get("selection_soft")
        rows.append(row)
    return rows


def _fmt(x) -> str:
    return "—" if x is None else f"{x:.3f}"


def _val_setup(run_dir: Path) -> str:
    cfg = _read_json(run_dir / "config.json") or {}
    items = _read_json(resolve(cfg.get("split_dir", "")) / "val" / "items.json") or []
    reps = int(cfg.get("val_repeats", 1))
    return f"{len(items)} val tasks × {reps} repeat{'s' if reps > 1 else ''}"


def _history_md(rows: list[dict], run_dir: Path, ledger: dict | None) -> str:
    lines = [
        "# C3 skill lineage (SkillOpt on WebMall)", "",
        f"Val F1 = mean per-task F1 over {_val_setup(run_dir)} (the gate score); "
        "val CR = mean task completion. ★ = became the new best skill; the last ★ is `SKILL.md`.", "",
        "| Version | Epoch | Parent | Edits | Val F1 before → after | Val CR | Decision | Best |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['version']} | {r['epoch']} | {r['parent'] or '—'} | {r['edits'] or '—'} | "
                     f"{_fmt(r['f1_before'])} → {_fmt(r['f1_after'])} | {_fmt(r['cr'])} | "
                     f"{r['decision']} | {'★' if r['best'] else ''} |")
    lines += ["", "## WebMall aggregate metrics of accepted versions (val)", "",
              "| Version | CR | P | R | F1 | Env errors |", "|---|---|---|---|---|---|"]
    for r in rows:
        if r["decision"] not in ("seed", "accepted"):
            continue
        sub = ("selection_eval_baseline" if r["version"] == "v0000"
               else f"steps/step_{int(r['version'][1:]):04d}/selection_eval")
        summary = _read_json(run_dir / sub / "summary.json") or {}
        w = summary.get("webmall") or {}
        lines.append(f"| {r['version']} | {_fmt(w.get('avg_task_completion_rate'))} | "
                     f"{_fmt(w.get('avg_precision'))} | {_fmt(w.get('avg_recall'))} | "
                     f"{_fmt(w.get('avg_f1_score'))} | {summary.get('env_errors', 0)} |")
    if ledger:
        lines += ["", f"Cost: ${ledger.get('total_usd', 0):.2f} total "
                      f"(target ${ledger.get('target_usd', 0):.2f}, optimizer ${ledger.get('optimizer_usd', 0):.2f}), "
                      f"{ledger.get('rollouts', 0)} rollouts; ledger shared by pilot and full run."]
    return "\n".join(lines) + "\n"


def export(run_dir: Path, out_dir: Path, base_skill: Path, ledger: Path | None) -> None:
    run_dir, out_dir = Path(run_dir), Path(out_dir)
    rows = build_rows(run_dir)
    texts = {"v0000": Path(base_skill).read_text(encoding="utf-8")}
    if out_dir.exists():
        shutil.rmtree(out_dir)
    hist = out_dir / "history"
    hist.mkdir(parents=True)
    (hist / "v0000_base.md").write_text(texts["v0000"], encoding="utf-8")
    for r in rows[1:]:
        sdir = run_dir / "steps" / f"step_{int(r['version'][1:]):04d}"
        cand = sdir / "candidate_skill.md"
        if r["decision"].startswith("skipped") or not cand.exists():
            continue
        text = cand.read_text(encoding="utf-8")
        texts[r["version"]] = text
        (hist / f"{r['version']}.md").write_text(text, encoding="utf-8")
        diff = difflib.unified_diff(texts[r["parent"]].splitlines(keepends=True),
                                    text.splitlines(keepends=True),
                                    fromfile=f"{r['parent']}.md", tofile=f"{r['version']}.md")
        (hist / f"{r['version']}.diff").write_text("".join(diff), encoding="utf-8")
        if (sdir / "ranked_edits.json").exists():
            shutil.copyfile(sdir / "ranked_edits.json", hist / f"{r['version']}.edits.json")
    best = [r["version"] for r in rows if r["best"]][-1]
    best_text = (run_dir / "best_skill.md").read_text(encoding="utf-8")
    if best_text.strip() != texts[best].strip():
        raise ValueError(f"best_skill.md does not match the last ★ version {best}")
    (out_dir / "SKILL.md").write_text(best_text, encoding="utf-8")
    ledger_data = _read_json(Path(ledger)) if ledger else None
    (out_dir / "HISTORY.md").write_text(_history_md(rows, run_dir, ledger_data), encoding="utf-8")
    (out_dir / "README.md").write_text(README, encoding="utf-8")
    if (run_dir / "summary.md").exists():  # written by webmall_skills.skillopt_webmall.report
        shutil.copyfile(run_dir / "summary.md", out_dir / "SUMMARY.md")
    run_out = out_dir / "run"
    run_out.mkdir()
    for name in ("config.json", "history.json"):
        if (run_dir / name).exists():
            shutil.copyfile(run_dir / name, run_out / name)
    split_dir = (_read_json(run_dir / "config.json") or {}).get("split_dir")
    if split_dir and (resolve(split_dir) / "split_manifest.json").exists():
        shutil.copyfile(resolve(split_dir) / "split_manifest.json", run_out / "split_manifest.json")
    if ledger_data is not None:
        (run_out / "cost.json").write_text(json.dumps(ledger_data, indent=2, sort_keys=True) + "\n")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("run_dir", type=Path)
    p.add_argument("--out", type=Path, default=SKILLS_DIR / "skillopt")
    p.add_argument("--base", type=Path, default=SKILLS_DIR / "base/SKILL.md")
    p.add_argument("--ledger", type=Path, default=None)
    args = p.parse_args()
    export(args.run_dir, args.out, args.base, args.ledger)
    print(f"exported {args.run_dir} -> {args.out}")


if __name__ == "__main__":
    main()
