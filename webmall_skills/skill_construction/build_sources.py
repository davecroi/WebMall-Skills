"""Generate skills/base/construction/sources.md from the allowed inputs.

Usage (from the repo root): python -m webmall_skills.skill_construction.build_sources
"""

import html
import json
import re
from pathlib import Path

from webmall_skills.paths import REPO_ROOT, SKILLS_DIR, TASK_SETS_PATH

OUT_PATH = SKILLS_DIR / "base/construction/sources.md"

# Neutral paraphrases for phrases that mirror a benchmark task (applied to the
# category prose in build_sources_md).
REDACTIONS: dict[str, str] = {
    "finding compatible CPUs for a motherboard": "finding parts that work with another given part",
    "the lowest price on a named product": "the best price for a product identified by name",
}


def general_instruction_block(task_sets_path: Path = TASK_SETS_PATH) -> str:
    task_sets = json.loads(Path(task_sets_path).read_text(encoding="utf-8"))
    blocks = {t["instruction"] for s in task_sets for t in s["tasks"]}
    if len(blocks) != 1:
        raise ValueError(f"expected one shared instruction block, found {len(blocks)}")
    return blocks.pop().replace("\\n", "\n").strip()


def _text(fragment: str) -> str:
    fragment = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()


def category_descriptions(index_html: Path) -> str:
    page = Path(index_html).read_text(encoding="utf-8")
    prose = _text(page)
    start = prose.index("The WebMall benchmark covers")
    end = prose.index("Each task is defined")
    lines = [prose[start:end].strip(), "", "| Task category | Task group | Count |", "|---|---|---|"]
    # Category table: drop the Examples cell. Rows that start a group carry an
    # extra (rowspan) group cell: [category, group, count, examples]; the others
    # have [category, count, examples].
    table = page[page.index("Task Categories Overview"):]
    table = table[: table.index("</table>")]
    group = ""
    for row in re.findall(r"<tr[^>]*>(.*?)</tr>", table, flags=re.S):
        cells = [_text(c) for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, flags=re.S)]
        if not cells or cells[0] == "Task Category":
            continue
        if len(cells) >= 4:
            category, group, count = cells[0], cells[1], cells[2]
        else:
            category, count = cells[0], cells[1]
        lines.append(f"| {category} | {group} | {count} |")
    return "\n".join(lines)


def prompt_layout(task_message: Path) -> str:
    lines = Path(task_message).read_text(encoding="utf-8").splitlines()
    out, keep = [], True
    for line in lines:
        if line.startswith("Agent Message:"):
            break  # the recorded agent reply mentions the example task
        if line.startswith("## Goal:"):
            out += [line, "<general instruction block, see section 1>", "<task>", "<task-specific request>", "</task>", ""]
            keep = False
        elif line.startswith("# Observation of current step:"):
            out += [line, "## Currently open tabs:", "<tabs>", "## AXTree:"]
            keep = False
        elif line.startswith("Note:") and not keep and out[-1] == "## AXTree:":
            out.append(line)
            keep = "notes"
        elif line.startswith("## Focused element:"):
            out += ["<accessibility tree of the current page>", "", line, "<focused element>", ""]
            keep = False
        elif line.startswith("# History of interaction with the task:"):
            out += [line, "<previous steps: thoughts, memory, actions>", ""]
            keep = False
        elif line.startswith("# Action space:"):
            keep = True
            out.append(line)
        elif keep is True or (keep == "notes" and not line.startswith("RootWebArea")):
            out.append(line)
        elif keep == "notes":
            keep = False
    return "\n".join(out).strip()


def build_sources_md() -> str:
    categories = category_descriptions(REPO_ROOT / "website/index.html")
    for phrase, paraphrase in REDACTIONS.items():
        categories = categories.replace(phrase, paraphrase)
    return "\n".join([
        "# Allowed sources for the WebMall base skill",
        "",
        "Generated by `skill_construction/build_sources.py`. Contains only environment- and",
        "category-level information; no task instances.",
        "",
        "## 1. General task instruction (identical in all 91 tasks)",
        "",
        "```",
        general_instruction_block(),
        "```",
        "",
        "Note: the example submission URLs in this block are part of the general instruction that",
        "the agent sees in every task, so the contamination check reports them; they are kept on purpose.",
        "",
        "## 2. Task categories (WebMall website, example tasks removed)",
        "",
        categories,
        "",
        "## 3. Agent prompt layout (examples/task_message.txt, task-specific parts replaced)",
        "",
        "```",
        prompt_layout(REPO_ROOT / "examples/task_message.txt"),
        "```",
        "",
    ])


if __name__ == "__main__":
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(build_sources_md(), encoding="utf-8")
    print(f"wrote {OUT_PATH}")
